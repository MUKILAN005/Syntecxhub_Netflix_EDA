import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt
data = pd.read_csv("Netflix_EDA.csv")
print(data.columns.tolist())
print(data.head())
print(data.shape)
print(data.dtypes)
print(data.isnull)
print("|nContent Type Count:")
print(data["type"].value_counts())
print(data["release_year"].value_counts().sort_index())
genres = data["listed_in"].dropna().str.split(",").explode()
print(genres.value_counts().head(10))
plt.figure(figsize=(6, 4))
sns.countplot(x="type", data=data)
plt.title("Netflix Content by type")
plt.xlabel("Content Type")
plt.ylabel("Count")
plt.show()
year_counts = data["release_year"].value_counts().sort_index()
plt.figure(figsize=(10,5))
plt.plot(year_counts.index, year_counts.values)
plt.title("Netflix Content Growth by Release Year")
plt.xlabel("Release Year")
plt.ylabel("Number of Titles")
plt.grid(True)
plt.show()
runtime = data["duration"].dropna()
runtime_numbers = runtime.str.extract(r"(\d+)")[0].astype(float)
plt.figure(figsize=(10, 5))
plt.hist(runtime_numbers, bins=20)
plt.title("Netflix Runtime Distribution")
plt.xlabel("Runtime (Minutes / Seasons)")
plt.ylabel("Number of Titles")
plt.show()